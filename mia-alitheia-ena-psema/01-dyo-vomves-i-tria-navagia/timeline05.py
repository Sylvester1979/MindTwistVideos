def words(txt):
    return re.sub(r'\[[^\]]*\]', ' ', txt).split()

def estimate():
    t = LEAD; out = {}
    for key, txt in BEATS:
        n = len(words(txt))
        t1 = t + n / RATE
        out[key] = [round(t, 3), round(t1, 3)]
        t = t1 + GAP + PAUSE * txt.count('[pause]') + LONG * txt.count('[long pause]')
        if key == 'q_true': t += COUNTDOWN
        t += BRIDGE.get(key, 0.0)
    out['_end'] = [round(t + 1.5, 3), round(t + 1.5, 3)]
    return out

if __name__ == '__main__':
    tl = estimate()
    os.makedirs(ROOT, exist_ok=True)
    json.dump(tl, open(f'{ROOT}/timeline.json', 'w'), ensure_ascii=False, indent=1)
    for k, (a, b) in tl.items():
        print(f'{k:12s} {a:7.2f} {b:7.2f}')
